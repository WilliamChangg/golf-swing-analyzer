#!/usr/bin/env python3
"""Capture documentation evidence, or render/check its appendix without inference.

Run from the repository root with the project's Python environment. Capturing
requires a real local clip and installed pose models; rendering uses only the
committed evidence and the standard library. Failed runs never replace evidence.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import statistics
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs/benchmarks/phase20.json"
APPENDIX = ROOT / "docs/benchmarks.md"


def output(argv: list[str]) -> str:
    return subprocess.check_output(argv, cwd=ROOT, text=True)


def capture(video: Path, repeats: int) -> dict:
    video = video.resolve()
    jobs = {
        "workflow": [
            "scripts/benchmark.py",
            str(video),
            "--repeats",
            str(repeats),
            "--json",
        ],
        "models": ["scripts/benchmark_models.py", str(video)],
        "reconstruction_noise": [
            "scripts/benchmark_reconstruct.py",
            "--sweep",
            "noise",
            "--repeats",
            str(repeats),
        ],
        "spatial_metrics": [
            "scripts/benchmark_reconstruct.py",
            "--sweep",
            "metrics",
            "--repeats",
            str(repeats),
        ],
    }
    record = {
        "schema_version": 1,
        "captured_at": datetime.now(timezone.utc).isoformat(),
        "revision": output(["git", "rev-parse", "HEAD"]).strip(),
        "working_tree_status": output(["git", "status", "--short"]),
        "platform": platform.platform(),
        "machine": platform.machine(),
        "python": platform.python_version(),
        "environment": {
            name: os.environ[name]
            for name in (
                "GSA_CACHE_DIR",
                "GSA_MODELS_DIR",
                "GSA_FORCE_CPU",
                "GSA_DISABLE_ANALYSIS_CACHE",
            )
            if name in os.environ
        },
        "hardware": output(["sysctl", "-n", "machdep.cpu.brand_string"]).strip()
        if sys.platform == "darwin"
        else platform.processor(),
        "source_sha256": {},
        "runs": {},
    }
    # Retain fingerprints of the engine, fixtures and scripts that affect these
    # runs, including uncommitted changes; a revision alone cannot describe them.
    sources = [ROOT / "models/manifest.json"]
    for directory in ("python/analyzer", "python/tests", "scripts"):
        sources.extend(sorted((ROOT / directory).rglob("*.py")))
    record["source_sha256"] = {
        str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sources
    }
    for name, argv in jobs.items():
        print(f"Capturing {name}", file=sys.stderr)
        raw = output([sys.executable, *argv])
        record["runs"][name] = {
            "executed_command": [sys.executable, *argv],
            "command": ["uv", "run", "--project", "python", "python", *argv],
            "output": json.loads(raw) if name in {"workflow", "models"} else raw,
        }
    return record


def render(record: dict) -> str:
    runs = record["runs"]
    workflow = runs["workflow"]["output"]
    models = runs["models"]["output"]
    lines = [
        "# Benchmark appendix",
        "",
        "Generated by `scripts/document_benchmarks.py`; do not edit the figures by hand.",
        "",
        "Source: [retained benchmark output](benchmarks/phase20.json).",
        f"Captured {record['captured_at']} on {record['hardware']} ({record['machine']}),",
        f"{record['platform']}, Python {record['python']}.",
        "",
        f"Engine revision: `{record['revision']}`. The source record also retains",
        "working-tree status, SHA-256 fingerprints of engine/fixture/script sources,",
        "commands, model hashes, configuration and individual timing samples.",
        "",
        "## Desktop analysis on real footage",
        "",
        "Source command: `scripts/benchmark.py` (full arguments in the source record).",
        f"Input: `{Path(workflow['input']['path']).name}`, {workflow['input']['frames']} frames;",
        f"{workflow['repeats']} measured repetitions per mode. Values below are medians",
        "computed from the retained runs, in milliseconds.",
        "",
        "Baseline forces fresh extraction and disables small result caches. Warm",
        "runs follow one untimed priming workflow. Neither mode deletes existing",
        "user caches. These are elapsed times, not landmark-accuracy measurements.",
        "",
        "<!-- prettier-ignore -->",
        "| Operation | Baseline (ms) | Warm (ms) | Baseline / warm |",
        "| --- | ---: | ---: | ---: |",
    ]
    medians = {}
    for mode in ("baseline", "warm"):
        grouped: dict[str, list[float]] = {}
        for run in workflow[mode]["runs"]:
            for entry in run:
                grouped.setdefault(entry["operation"], []).append(entry["elapsed_s"])
        medians[mode] = {
            name: statistics.median(values) for name, values in grouped.items()
        }
    for name, baseline in medians["baseline"].items():
        warm = medians["warm"][name]
        lines.append(
            f"| `{name}` | {baseline * 1000:.2f} | {warm * 1000:.2f} | {baseline / warm:.2f}× |"
        )
    lines += [
        "",
        "The input content key and requested filter configuration are in",
        "`runs.workflow.output.input` and `runs.workflow.output.config` in the JSON.",
        "On macOS, retained RSS samples are process peak RSS, not per-stage allocations.",
        "",
        "## Model execution on CPU",
        "",
        "Source command: `scripts/benchmark_models.py`; one fresh extraction.",
        "",
        f"- Inventory verification: {models['inventory_verify_ms']:.2f} ms.",
        f"- Pose delegate: `{models['pose_delegate']}`.",
        f"- Temporal output device: `{models['temporal_device']}`.",
        f"- Temporal output finite: `{str(models['temporal_output_finite']).lower()}`.",
        "",
        "The full pose statistics and verified model digests are retained under",
        "`runs.models.output`. A successful run establishes execution, not accuracy.",
        "",
    ]
    for name, title in (
        ("reconstruction_noise", "Synthetic reconstruction error"),
        ("spatial_metrics", "Synthetic spatial metric error"),
    ):
        lines += [
            f"## {title}",
            "",
            "Source command:",
            "",
            "```text",
            " ".join(runs[name]["command"]),
            "```",
            "",
            "The following is the benchmark's own output. The body and cameras",
            "are synthetic inputs; no pose estimator, real calibration capture,",
            "occlusion or motion blur is evaluated. These figures are floors,",
            "not accuracy claims on golfers.",
            "",
            "```text",
            runs[name]["output"].rstrip(),
            "```",
            "",
        ]
    lines += [
        "## Reproduce or refresh",
        "",
        "From the repository root, after installing dependencies and pose models:",
        "",
        "```bash",
        "uv run --project python python scripts/document_benchmarks.py --capture --video path/to/swing.mp4 --repeats 5",
        "python3 scripts/document_benchmarks.py",
        "python3 scripts/document_benchmarks.py --check",
        "```",
        "",
        "Capture replaces the evidence only after every benchmark succeeds. Rendering",
        "and checking need no models, private footage, network or third-party Python",
        "packages. The original video is local and uncommitted; a different input",
        "produces a new experiment, not a reproduction of this one.",
        "",
        "Historical tables in the roadmap and ADRs record earlier runs. They were",
        "not regenerated from this evidence, and their raw outputs were not retained",
        "with this appendix. Use this appendix for the current traceable figures.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--capture", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--video", type=Path)
    parser.add_argument("--repeats", type=int, default=5)
    args = parser.parse_args()
    if args.capture:
        if args.video is None or not args.video.is_file() or args.repeats < 1:
            parser.error(
                "--capture requires an existing --video and positive --repeats"
            )
        record = capture(args.video, args.repeats)
        EVIDENCE.parent.mkdir(parents=True, exist_ok=True)
        temporary = EVIDENCE.with_suffix(".tmp")
        temporary.write_text(json.dumps(record, indent=2) + "\n")
        temporary.replace(EVIDENCE)
    else:
        record = json.loads(EVIDENCE.read_text())
    content = render(record)
    if args.check:
        if not APPENDIX.exists() or APPENDIX.read_text() != content:
            print(
                "Benchmark appendix is stale; run scripts/document_benchmarks.py",
                file=sys.stderr,
            )
            return 1
        print("Benchmark appendix matches retained evidence.")
    else:
        APPENDIX.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
